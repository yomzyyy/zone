import type { NextConfig } from "next";

// Security headers applied to every response. Vercel sets HSTS at the platform
// level on its own, but we also send it explicitly so the same protections
// apply on any other host.
// CSP is the cheap second layer behind DOMPurify — even if user content
// somehow bypassed sanitization, the browser would still refuse to execute
// inline scripts from anywhere except our own origin (plus inline tolerated
// for Next's hydration). 'unsafe-eval' is needed in dev for HMR; production
// gets the stricter policy below.
const isDev = process.env.NODE_ENV !== "production";
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'" + (isDev ? " 'unsafe-eval'" : ""),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://api.resend.com",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const securityHeaders = [
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), interest-cohort=()",
  },
  { key: "Content-Security-Policy", value: csp },
];

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
